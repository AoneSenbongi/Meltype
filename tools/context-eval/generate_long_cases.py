def make_case(group, sense, cue, variant, index, split):
    reading, surfaces, contexts = GROUPS[group]
    left, right, prefix = contexts[sense][cue], "", ""
    if variant == 1:
        left = "作業メモ。" + left
    elif variant == 2:
        left, right = "", "。" + left
    elif variant == 3:
        right = "。内容をもう一度確認する。"
    elif variant == 4:
        prefix = "GitHub: "
    candidates = [prefix + s for s in surfaces]
    if (group + sense + cue + variant) % 2:
        candidates.reverse()
    return dict(id=f"{split}-{index:04d}", split=split, family=f"pair-{group + 1:02d}",
                reading=prefix + reading, left=left, right=right, candidates=candidates,
                expected=prefix + surfaces[sense], reviewed=(group + 2 * cue + sense + variant) % 4 == 0,
                undo=split == "stream" and index % 37 == 0)


def generate():
    stream = []
    for variant in range(5):
        for sense in range(2):
            for cue in range(5):
                for group in range(20):
                    stream.append(make_case(group, sense, cue, variant, len(stream) + 1, "stream"))
    probes = [make_case(g, s, 5, 0, 2 * g + s + 1, "probe") for g in range(20) for s in range(2)]
    keys = [(c["reading"], c["left"], c["right"]) for c in stream + probes]
    assert len(stream) == 1000 and len(probes) == 40 and len(set(keys)) == 1040
    assert all(c["expected"] in c["candidates"] for c in stream + probes)
    assert sum(c["reviewed"] for c in stream) == 250
    corpus = dict(stream=stream, probes=probes)
    path = Path(__file__).with_name("long-cases.json")
    payload = json.dumps(corpus, ensure_ascii=False, indent=2).encode("utf-8")
    path.write_bytes(payload)
    manifest = dict(stream=1000, probes=40, homophone_pairs=20, semantic_examples=200, variants=5,
                    reviewed=250, undone=sum(c["undo"] for c in stream), seed="deterministic-v1",
                    sha256=hashlib.sha256(payload).hexdigest(),
                    limitations=["Synthetic templates, not 1000 independent meanings.", "Expected labels are authored choices, not human usability scores."])
    path.with_name("long-cases-manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False))


if __name__ == "__main__":
    generate()
